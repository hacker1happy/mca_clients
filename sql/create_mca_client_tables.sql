-- Oracle-compatible DDL for MCA client file imports.
-- Assumption: COMPANIES already exists and contains SEQ_NO.
-- If COMPANIES.SEQ_NO already has a primary key, skip the first ALTER TABLE.

ALTER TABLE COMPANIES
  ADD CONSTRAINT PK_COMPANIES PRIMARY KEY (SEQ_NO);

CREATE TABLE FILES (
  FILE_NUMBER NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  FILE_NAME VARCHAR2(500) NOT NULL,
  COMPANY_NUMBER NUMBER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_FILES PRIMARY KEY (FILE_NUMBER),
  CONSTRAINT FK_FILES_COMPANIES
    FOREIGN KEY (COMPANY_NUMBER) REFERENCES COMPANIES (SEQ_NO),
  CONSTRAINT UQ_FILES_COMPANY_FILE
    UNIQUE (COMPANY_NUMBER, FILE_NAME)
);

CREATE TABLE CLIENTS (
  CLIENT_SEQUENCE_NUMBER NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NAME_OF_SHAREHOLDER VARCHAR2(500),
  FOLIO_REFERENCE_NUMBER VARCHAR2(200),
  DP_CLIENT_ACCOUNT VARCHAR2(200),
  TYPE_OF_IDENTIFIER VARCHAR2(100),
  IDENTIFICATION_NO VARCHAR2(200),
  OCCUPATION VARCHAR2(200),
  NUMBER_OF_SECURITY_HELD NUMBER,
  TOTAL_SECURITY_AMOUNT_INR NUMBER(18, 2),
  FILE_NUMBER NUMBER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CLIENTS PRIMARY KEY (CLIENT_SEQUENCE_NUMBER),
  CONSTRAINT FK_CLIENTS_FILES
    FOREIGN KEY (FILE_NUMBER) REFERENCES FILES (FILE_NUMBER)
);

CREATE INDEX IDX_FILES_COMPANY_NUMBER ON FILES (COMPANY_NUMBER);
CREATE INDEX IDX_CLIENTS_FILE_NUMBER ON CLIENTS (FILE_NUMBER);
