-- Oracle-compatible DDL for MCA client file imports.
-- Assumption: COMPANIES already exists and contains SEQ_NO.
-- If COMPANIES.SEQ_NO already has a primary key, skip the first ALTER TABLE.

ALTER TABLE COMPANIES
  ADD CONSTRAINT PK_COMPANIES PRIMARY KEY (COMP_ID);

CREATE TABLE FILES (
  FILE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  FILE_NAME VARCHAR2(500) NOT NULL,
  COMPANY_ID NUMBER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_FILES PRIMARY KEY (FILE_ID),
  CONSTRAINT FK_FILES_COMPANIES
    FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (COMP_ID),
  CONSTRAINT UQ_FILES_COMPANY_FILE
    UNIQUE (COMPANY_ID, FILE_NAME)
);

CREATE TABLE MCA_CLIENTS (
  CLIENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NAME_OF_SHAREHOLDER VARCHAR2(500),
  FOLIO_NUMBER VARCHAR2(200),
  DP_CLIENT_ACCOUNT VARCHAR2(200),
  TYPE_OF_IDENTIFIER VARCHAR2(100),
  IDENTIFICATION_NO VARCHAR2(200),
  OCCUPATION VARCHAR2(200),
  NUMBER_OF_SECURITY_HELD NUMBER,
  TOTAL_SECURITY_AMOUNT_INR NUMBER(18, 2),
  FILE_ID NUMBER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CLIENTS PRIMARY KEY (CLIENT_ID),
  CONSTRAINT FK_CLIENTS_FILES
    FOREIGN KEY (FILE_ID) REFERENCES FILES (FILE_ID)
);

CREATE INDEX IDX_FILES_ID ON FILES (COMPANY_ID);
CREATE INDEX IDX_CLIENTS_ID ON MCA_CLIENTS (FILE_ID);

COMMIT;